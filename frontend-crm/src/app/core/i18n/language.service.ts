/**
 * Textos con números en medio («Día 4», «82 días», «(0 de 1)», «1–8 de 23»):
 * una frase fija no los cubre y «de» suelto rompería otras palabras.
 */
const NUMBER_PATTERNS: ReadonlyArray<readonly [RegExp, string]> = [
  [/^Día (\d+)$/, 'Day $1'],
  [/(\d+) días\b/g, '$1 days'],
  [/(\d+) día\b/g, '$1 day'],
  [/([\d,.$]+) de ([\d,.$]+)/g, '$1 of $2'],
];

@Injectable({ providedIn: 'root' })
export class LanguageService {
  private readonly session = inject(SessionContext);
  private readonly access = inject(AccessStore);
  readonly language = signal<AppLanguage>(this.readStoredLanguage());

  constructor() {
    document.documentElement.lang = this.language() === 'en' ? 'en' : 'es-MX';
  }

  t(source: string): string {
    return this.translate(source, this.language());
  }

  translate(source: string, language: AppLanguage): string {
    if (language !== 'en') return source;
    const exact = ENGLISH[source];
    if (exact) return exact;
    // «Hace 4 min» → «4 min ago»: el orden cambia, así que no sirve una frase.
    const ago = /^Hace (\d+) (min|h|d)$/.exec(source);
    if (ago) return `${ago[1]} ${ago[2]} ago`;
    // «＋ Nuevo cliente», «⇩ Exportar», «Ver la red ›»: se traduce el texto y se
    // conservan los símbolos de los extremos.
    const framed = /^([^\p{L}\p{N}¿¡«$]+)?(.*?)([^\p{L}\p{N}.!?»)%]+)?$/u.exec(source);
    if (framed && (framed[1] || framed[3])) {
      const core = ENGLISH[framed[2]];
      if (core) return `${framed[1] ?? ''}${core}${framed[3] ?? ''}`;
    }
    const phrased = ENGLISH_PHRASES.reduce(
      (translated, [spanish, english]) => translated.replaceAll(spanish, english),
      source,
    );
    return NUMBER_PATTERNS.reduce((translated, [pattern, english]) => translated.replace(pattern, english), phrased);
  }

  setLanguage(language: AppLanguage): void {
    this.language.set(language);
    localStorage.setItem('speedlink-language', language);
    document.documentElement.lang = language === 'en' ? 'en' : 'es-MX';
    const userId = this.session.user()?.id;
    if (userId) this.access.setPreferredLanguage(userId, language);
  }

  locale(): string {
    return this.language() === 'en' ? 'en-US' : 'es-MX';
  }

  private readStoredLanguage(): AppLanguage {
    const stored = localStorage.getItem('speedlink-language');
    if (stored === 'en' || stored === 'es') return stored;
    return this.session.user()?.preferredLanguage === 'en' ? 'en' : 'es';
  }
}
